-- Exporte la STRUCTURE de la base GMAO (aucune donnee) en un seul texte. LECTURE SEULE.
-- Supabase > SQL Editor : coller, Run, puis Export > Download CSV.
with t as (
  select c.oid, c.relname, c.relrowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p')
),
morceaux as (
  select 0 as ordre, '' as nom, '-- ' || version() as def
  union all
  select 1, e.extname::text, format('-- extension %s %s', e.extname, e.extversion) from pg_extension e
  union all
  select 2, ty.typname::text, format('cre' || 'ate type public.%I as enum (%s);', ty.typname,
         string_agg(quote_literal(en.enumlabel), ', ' order by en.enumsortorder))
  from pg_type ty join pg_enum en on en.enumtypid = ty.oid join pg_namespace n on n.oid = ty.typnamespace
  where n.nspname = 'public' group by ty.typname
  union all
  select 3, c.relname::text, format('cre' || 'ate sequence if not exists public.%I;', c.relname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
  union all
  select 4, t.relname::text, format(E'cre' || E'ate ta' || E'ble public.%I (\n%s\n);', t.relname,
         string_agg(format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
           case
             when a.attidentity = 'a' then ' generated always as identity'
             when a.attidentity = 'd' then ' generated by default as identity'
             when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
             when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid)
             else ''
           end,
           case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum))
  from t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  group by t.relname
  union all
  select case when k.contype = 'f' then 6 else 5 end, t.relname || '.' || k.conname,
         format('al' || 'ter ta' || 'ble public.%I add constraint %I %s;', t.relname, k.conname, pg_get_constraintdef(k.oid))
  from pg_constraint k join t on t.oid = k.conrelid
  where k.contype in ('p', 'u', 'c', 'f', 'x')
  union all
  select 7, i.indexrelid::regclass::text, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join t on t.oid = i.indrelid
  where not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)
  union all
  select 8, p.proname::text, pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  select 9, c.relname::text, format(E'cre' || E'ate view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid, true))
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
  union all
  select 10, g.tgname::text, pg_get_triggerdef(g.oid) || ';'
  from pg_trigger g join t on t.oid = g.tgrelid where not g.tgisinternal
  union all
  select 11, t.relname::text, format('al' || 'ter ta' || 'ble public.%I en' || 'able row level security;', t.relname)
  from t where t.relrowsecurity
  union all
  select 12, p.tablename || '.' || p.policyname,
         format('cre' || 'ate policy %I on public.%I as %s for %s to %s%s%s;', p.policyname, p.tablename,
           lower(p.permissive), lower(p.cmd), array_to_string(p.roles, ', '),
           coalesce(' using (' || p.qual || ')', ''), coalesce(' with check (' || p.with_check || ')', ''))
  from pg_policies p where p.schemaname = 'public'
  union all
  select 13, b.id, format('-- espace de stockage %s (public : %s)', b.id, b.public) from storage.buckets b
)
select string_agg(def, E'\n\n' order by ordre, nom) as structure_gmao from morceaux;
